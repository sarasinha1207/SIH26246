#!/usr/bin/env python3
"""
Phase 8 - post-evaluation summaries (no model is touched) and the xgboost_v2 model card.

Reads data/interim/phase8_test_predictions.parquet and the frozen files.  Writes reports/evaluation/test/extra_comparisons.csv (paired bootstrap of the fold-chosen
blend against the baseline and the declared model, and the 2025-26-only scores) and models/xgboost_v2/model_card.md.
Run: python src/evaluation/make_report.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
for sub in ("common", "training", "evaluation"):
    sys.path.insert(0, str(ROOT / "src" / sub))
import lmis_data as ld  # noqa: E402
import splits as sp  # noqa: E402
from evaluate import bootstrap_diff, matrices, mh, wape  # noqa: E402
import tune_optuna as to  # noqa: E402

V2 = ROOT / "models" / "xgboost_v2"
OUT = ROOT / "reports" / "evaluation"
T = OUT / "test"
NAMES = ld.NAMES


def table(header, rows):
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def f(v):
    if isinstance(v, float):
        return f"{v:g}" if v == round(v, 4) else f"{v:.4f}"
    return str(v)


def main():
    pred = pd.read_parquet(ROOT / "data" / "interim" / "phase8_test_predictions.parquet")
    rng = np.random.default_rng(7)
    rows, late_rows = [], []
    for k in "EVS":
        S = pred[(pred.target == k) & ~pred.shock].reset_index(drop=True)
        base = "seasonal_naive_drift" if k == "E" else "last_plus_seasonal_shift"
        cols = ["primary", "cv_blend", "v1_refit", base]
        A, D = matrices(S, cols)
        for a, b in (("cv_blend", base), ("cv_blend", "primary"), ("cv_blend", "v1_refit"), ("primary", base), ("primary", "v1_refit")):
            lo, hi = bootstrap_diff(A, D, a, b, rng)
            rows.append(dict(target=k, comparison=f"{a} minus {b}", wape_a=mh(S, a), wape_b=mh(S, b), diff=mh(S, a) - mh(S, b), ci_low=lo, ci_high=hi))
        late = S[S.target_date >= "2025-01-01"]
        late_rows.append(dict(target=k, window="2025-01 to 2026-12", primary=mh(late, "primary"), cv_blend=mh(late, "cv_blend"), v1_refit=mh(late, "v1_refit"), best_simple_baseline=mh(late, base), baseline_name=base))
    pd.DataFrame(rows).to_csv(T / "extra_comparisons.csv", index=False)
    pd.DataFrame(late_rows).to_csv(T / "scores_2025_26_only.csv", index=False)

    # ---- model card
    fr = json.load(open(V2 / "frozen_config.json"))
    prm = json.load(open(V2 / "primary" / "params.json"))
    fin = {k: json.load(open(OUT / f"finalize_{k}.json")) for k in "EVS"}
    res = json.load(open(OUT / "test_results.json"))["targets"]
    ov = pd.read_csv(T / "overall.csv")
    sc = pd.read_csv(T / "phase1_scorecard.csv").set_index("target")
    cov = pd.read_csv(T / "interval_coverage.csv")
    log = json.load(open(OUT / "test_access_log.json"))
    nt = {k: len(pd.read_csv(OUT / f"optuna_{k}_trials.csv")) for k in "EVS"}
    L = []
    add = L.append
    add("# Model card: tuned XGBoost forecaster (`xgboost_v2`)\n")
    add("*Generated by `src/evaluation/make_report.py` from the frozen files and the test evaluation; do not edit by hand. Supersedes `models/xgboost_v1` for Phase 8 results; v1 stays as the Phase 7 reference.*\n")
    add("## 1. What this is\n")
    add(f"Three XGBoost models (employed workers E, job vacancies V, registered seekers S), each a five-seed average, tuned with Optuna on train and validation data only ({nt['E']}, {nt['V']} and {nt['S']} trials), "
        "then refitted on train + validation. Directory `primary/` is the declared Phase 8 candidate; `train_only/`, `v1_refit/` (Phase 7 settings) and `challenger_hgb/` (HistGradientBoosting) are the pre-declared comparisons. "
        f"Everything was frozen at {fr['frozen_at']} (checksums in `frozen_config.json`) and the test split (2023-01 to 2026-12) was evaluated once ({len(log['runs'])} run in `reports/evaluation/test_access_log.json`).\n")
    add("## 2. Final hyper-parameters (`primary/params.json`)\n")
    keys = ["objective", "huber_slope", "learning_rate", "n_estimators", "max_leaves", "min_child_weight", "reg_lambda", "reg_alpha", "gamma", "subsample", "colsample_bytree", "colsample_bynode", "max_bin"]
    rows = []
    for key in keys:
        vals = []
        for k in "EVS":
            p = prm[k]["xgboost_params"]
            vals.append(f(p.get(key, "-")))
        rows.append((f"`{key}`", *vals))
    rows.append(("`recency_halflife` (months, 0 = no weighting)", *[str(prm[k]["config"].get("recency_halflife", 0)) for k in "EVS"]))
    rows.append(("tree_method / grow_policy / n_jobs", *["hist / lossguide / -1 (all cores)"] * 3))
    rows.append(("seeds averaged", *[str(prm[k]["seeds"]) for k in "EVS"]))
    rows.append(("chosen from", *[fin[k]["chosen"]["name"] for k in "EVS"]))
    add(table(["Parameter", "E", "V", "S"], rows))
    add("\nPhase 7 (v1) settings for comparison: learning rate 0.03 / 0.08 / 0.08, trees 300 / 40 / 250, leaves 63 / 63 / 31. V kept its Phase 7 configuration: no Optuna trial beat it by the required 1%.\n")
    add("## 3. How the settings were chosen\n")
    add("* **Search:** Optuna TPE (multivariate, 20 random start-up trials); the Phase 7 configuration and the Phase 6 default were the first two trials. Space: learning rate 0.01-0.1, leaves 4-127, min_child_weight 20-1500, L2 0.5-500, L1 0.001-10, gamma 0.0001-0.2, "
        "row sampling 0.4-1, column sampling 0.3-1 (tree) and 0.5-1 (split), bins {64, 128, 256}, loss {squared error, pseudo-Huber, absolute error}, recency half-life {none, 24, 60 months}. The tree count is the best of checkpoints up to min(600, 20 / learning rate).\n"
        "* **Objective:** mean over four folds (rolling origins 2016-12, 2017-12, 2018-12, and the validation split) of fold WAPE divided by the Phase 7 configuration's WAPE on that fold.\n"
        "* **Acceptance:** the five best trials, the Phase 7 settings and the Phase 6 default were re-scored with three seeds; the Phase 7 settings were replaced only by a candidate at least 1% better. E and S were replaced; V was not.\n"
        "* **Limit:** the seekers' best trials all used the 600-tree ceiling of the search, so a longer budget might have helped; and the seekers' search saw a validation fold that lies inside the e-Shram ramp (see Section 6).\n")
    add("## 4. Blend with the baseline and intervals\n")
    add("* **Blend (D4 from Phase 6):** per horizon, weight w on the model in w x model + (1 - w) x (last value + seasonal shift), chosen on out-of-sample predictions of the three rolling-origin folds, and used only if it improved that horizon by 1%. "
        "The folds chose weights 0.75 at horizons 1-2 for E and 0.5-0.75 from horizon 6 for S; none for V. A validation veto (drop a blend that makes validation WAPE more than 5% worse) was then applied: it dropped the seekers' blend because validation, which lies inside the registry ramp, was 41% worse with it. "
        "**On the test split that veto turned out to be wrong** (Section 5), so both versions are reported: `primary` (veto applied) and `cv_blend` (fold-chosen weights, `primary/blend_cv.json`).\n"
        f"* **Intervals:** 5% and 95% quantiles of the log errors in the rolling-origin folds by horizon, scaled by the median ratio of validation error spread to fold error spread (E x{fin['E']['interval_scale']:.2f}, V x{fin['V']['interval_scale']:.2f}, S x{fin['S']['interval_scale']:.2f}).\n")
    add("## 5. Test results (2023-01 to 2026-12, horizons 1-12, WAPE %)\n")
    rows = []
    for k in "EVS":
        o = ov[ov.target == k].set_index("model")
        bb = res[k]["best_baseline"]
        rows.append((f"{NAMES[k]} ({k})", f"{o.loc['primary', 'wape_mean_horizon']:.2f}", f"{o.loc['cv_blend', 'wape_mean_horizon']:.2f}", f"{o.loc['v1_refit', 'wape_mean_horizon']:.2f}", f"{o.loc['hgb', 'wape_mean_horizon']:.2f}",
                     f"{o.loc[bb, 'wape_mean_horizon']:.2f} ({bb.replace('_', ' ')})", f"{sc.loc[k, 'phase1_wape_limit']:g}"))
    add(table(["Target", "Phase 8 model (declared)", "+ fold-chosen blend", "Phase 7 settings", "HistGradientBoosting", "Best simple baseline", "Phase 1 limit"], rows))
    add("\nSeekers exclude the two ramp months (2023-01, 2023-02). Paired-bootstrap intervals, by-horizon, by-sector, by-year and by-tier tables: `reports/evaluation/test/`. Figures: `reports/evaluation/figures/`.\n")
    add("## 6. Limits\n")
    add("* The seekers' declared model is **worse than the simple baseline** on the test split, and worse than the Phase 7 settings; the tuning was fitted to the ramp-contaminated validation fold. The fold-chosen blend is the useful seekers model, but choosing it after seeing the test split means its test score carries a small selection bias (one of two pre-declared variants).\n"
        "* Vacancies are within a few percent of the simple baseline; the remaining error looks like the simulator's noise floor. Employed workers pass the Phase 1 accuracy limit.\n"
        "* The test split is now spent: any further tuning needs fresh data (Phase 10 monitoring).\n")
    (V2 / "model_card.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote extra_comparisons.csv and model_card.md")


if __name__ == "__main__":
    main()
